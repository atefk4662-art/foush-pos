def ascii_skeleton(line):
    """Strip all non-ASCII chars and sequences of ? that look like corrupted Arabic.
    Keep only the ASCII structural characters."""
    # Replace sequences of ? mixed with special chars that look like corrupted text
    # A corrupted Arabic segment looks like: ??"???^?"?? (? mixed with ASCII punctuation)
    result = []
    for ch in line:
        if ord(ch) > 127:  # Non-ASCII (Arabic in ZIP file)
            result.append('\x00')  # Placeholder
        elif ch == '?':
            result.append('\x00')  # Corrupted char placeholder
        else:
            result.append(ch)
    # Collapse consecutive placeholders
    s = ''.join(result)
    s = re.sub(r'\x00+', '\x00', s)
    return s

# Build skeleton index of ZIP lines
zip_skeleton_map = {}
for i, zline in enumerate(zip_lines):
    skel = ascii_skeleton(zline).strip()
    if skel and '\x00' in skel:  # Only lines that had Arabic
        if skel not in zip_skeleton_map:
            zip_skeleton_map[skel] = []
        zip_skeleton_map[skel].append(i)

# ============================================================
# STEP 2: Match current lines to ZIP lines
# ============================================================
matched = 0
unmatched_lines = []
restored_lines = []

for i, cline in enumerate(current_lines):
    if '?' not in cline:
        restored_lines.append(cline)
        continue
    
    # Check if this line has corrupted Arabic (? mixed with other chars in suspicious patterns)
    # Legitimate ? usage: ternary (?), optional chaining (?.), nullish coalescing (??)
    # Corrupted: ??"???^?"?? or ???'? or ?f?^?
    has_corrupted = bool(re.search(r'\?\?["\'^.SsfY]|["\'^.SsfY]\?\?|\?\?\?', cline))
    
    if not has_corrupted:
        restored_lines.append(cline)
        continue
    
    skel = ascii_skeleton(cline).strip()
    if skel in zip_skeleton_map:
        # Found a match! Use the ZIP version
        zip_idx = zip_skeleton_map[skel][0]
        restored_lines.append(zip_lines[zip_idx])
        matched += 1
    else:
        restored_lines.append(cline)
        unmatched_lines.append((i + 1, cline.strip()[:120]))

print(f"Matched {matched} lines from ZIP file")
print(f"Unmatched corrupted lines: {len(unmatched_lines)}")

